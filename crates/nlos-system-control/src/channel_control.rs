/// Typed failures produced while handling a `ChannelControl` SABI request.
#[derive(Debug)]
pub enum ChannelControlError {
    /// Request or response payload violated the wire contract.
    Payload(CompatibilityError),
    /// Common SABI request context was missing or invalid.
    Common(CommonSemanticsError),
    /// Unknown service or method name.
    UnknownMethod,
    /// Policy boundary rejected the caller.
    AuthorizationDenied(&'static str),
    /// Mutation payload `idempotency_key` did not match the SABI request context key.
    IdempotencyKeyMismatch,
    /// A fixed-width byte identifier or digest was not 16 or 32 bytes.
    InvalidIdentifier,
    /// A generation field carried zero where a non-zero [`Generation`] is required.
    InvalidGeneration,
    /// `EnqueueChannelRequestWire` carried a half-populated producer registration.
    InvalidProducerRegistration,
    /// The backing [`ChannelControlBackend`] rejected the operation.
    Backend(ChannelBackendError),
}

impl fmt::Display for ChannelControlError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Payload(error) => write!(formatter, "invalid ChannelControl payload: {error}"),
            Self::Common(error) => write!(formatter, "invalid ChannelControl context: {error}"),
            Self::UnknownMethod => formatter.write_str("unknown ChannelControl service or method"),
            Self::AuthorizationDenied(reason) => {
                write!(formatter, "ChannelControl authorization denied: {reason}")
            }
            Self::IdempotencyKeyMismatch => formatter
                .write_str("ChannelControl idempotency key does not match the request context"),
            Self::InvalidIdentifier => {
                formatter.write_str("ChannelControl payload identifier length is out of contract")
            }
            Self::InvalidGeneration => {
                formatter.write_str("ChannelControl generation field must be non-zero")
            }
            Self::InvalidProducerRegistration => formatter.write_str(
                "ChannelControl producer_binding and producer_fiber_generation must both be set or both be omitted",
            ),
            Self::Backend(error) => {
                write!(formatter, "ChannelAuthority rejected ChannelControl: {error}")
            }
        }
    }
}

impl Error for ChannelControlError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Payload(error) => Some(error),
            Self::Common(error) => Some(error),
            Self::Backend(error) => Some(error),
            Self::UnknownMethod
            | Self::AuthorizationDenied(_)
            | Self::IdempotencyKeyMismatch
            | Self::InvalidIdentifier
            | Self::InvalidGeneration
            | Self::InvalidProducerRegistration => None,
        }
    }
}

impl From<CompatibilityError> for ChannelControlError {
    fn from(error: CompatibilityError) -> Self {
        Self::Payload(error)
    }
}

impl From<CommonSemanticsError> for ChannelControlError {
    fn from(error: CommonSemanticsError) -> Self {
        Self::Common(error)
    }
}

impl From<ChannelBackendError> for ChannelControlError {
    fn from(error: ChannelBackendError) -> Self {
        Self::Backend(error)
    }
}

#[cfg(any(feature = "daemon", feature = "notify", test))]
impl From<nlos_channel::ChannelAuthorityError> for ChannelControlError {
    fn from(error: nlos_channel::ChannelAuthorityError) -> Self {
        Self::Backend(ChannelBackendError::from(error))
    }
}

impl ChannelControlError {
    /// Projects this failure into the bounded SABI failure contract.
    #[must_use]
    pub fn to_sabi_failure(&self) -> SabiFailure {
        let (code, retry, safe_message) = match self {
            Self::Payload(
                CompatibilityError::MissingSchemaIdentity
                | CompatibilityError::UnknownSchema(_)
                | CompatibilityError::UnsupportedMajor { .. }
                | CompatibilityError::UnsupportedCriticalExtension { .. },
            ) => (
                SabiErrorCode::AbiVersion,
                RetryDirective::DoNotRetry,
                "request payload schema identity is incompatible",
            ),
            Self::Payload(_) => (
                SabiErrorCode::InvalidArgument,
                RetryDirective::DoNotRetry,
                "request payload failed bounded validation",
            ),
            Self::Common(CommonSemanticsError::DeadlineExpired) => (
                SabiErrorCode::Deadline,
                RetryDirective::DoNotRetry,
                "request deadline expired before execution",
            ),
            Self::Common(_) => (
                SabiErrorCode::InvalidArgument,
                RetryDirective::DoNotRetry,
                "request common context failed validation",
            ),
            Self::UnknownMethod => (
                SabiErrorCode::NotSupported,
                RetryDirective::DoNotRetry,
                "unknown ChannelControl service or method",
            ),
            Self::AuthorizationDenied(_) => (
                SabiErrorCode::Rights,
                RetryDirective::DoNotRetry,
                "caller is not authorized for this ChannelControl operation",
            ),
            Self::IdempotencyKeyMismatch => (
                SabiErrorCode::Conflict,
                RetryDirective::DoNotRetry,
                "payload idempotency key does not match request context",
            ),
            Self::InvalidIdentifier => (
                SabiErrorCode::InvalidArgument,
                RetryDirective::DoNotRetry,
                "payload identifier or digest length is invalid",
            ),
            Self::InvalidGeneration => (
                SabiErrorCode::InvalidArgument,
                RetryDirective::DoNotRetry,
                "payload generation must be non-zero",
            ),
            Self::InvalidProducerRegistration => (
                SabiErrorCode::InvalidArgument,
                RetryDirective::DoNotRetry,
                "producer binding and fiber generation must both be present or both be absent",
            ),
            Self::Backend(error) => map_backend_error(error),
        };
        SabiFailure {
            code: code.into(),
            retry: retry.into(),
            safe_message: safe_message.to_owned(),
        }
    }
}

const fn map_backend_error(
    error: &ChannelBackendError,
) -> (SabiErrorCode, RetryDirective, &'static str) {
    match error {
        ChannelBackendError::ChannelNotFound(_) => (
            SabiErrorCode::NotFound,
            RetryDirective::DoNotRetry,
            "requested channel does not exist",
        ),
        ChannelBackendError::IdempotencyConflict => (
            SabiErrorCode::Conflict,
            RetryDirective::DoNotRetry,
            "idempotency key or consumption identity conflicts with durable channel state",
        ),
        ChannelBackendError::StaleChannel => (
            SabiErrorCode::Fenced,
            RetryDirective::DoNotRetry,
            "channel generation or fencing token is stale",
        ),
        ChannelBackendError::QueueFull => (
            SabiErrorCode::Quota,
            RetryDirective::DoNotRetry,
            "queue backlog plus payload exceeds channel capacity",
        ),
        ChannelBackendError::GenerationExhausted => (
            SabiErrorCode::Quota,
            RetryDirective::DoNotRetry,
            "channel generation space is exhausted",
        ),
        ChannelBackendError::InvalidCapacity
        | ChannelBackendError::InvalidPayload
        | ChannelBackendError::InvalidSequence(_)
        | ChannelBackendError::InvalidBindingRegistration => (
            SabiErrorCode::InvalidArgument,
            RetryDirective::DoNotRetry,
            "request violates the channel authority contract",
        ),
        ChannelBackendError::Sqlite(_) => (
            SabiErrorCode::Durability,
            RetryDirective::RetrySameIdempotencyKey,
            "channel authority storage is temporarily unavailable",
        ),
        ChannelBackendError::Io(_) | ChannelBackendError::DurabilityUnavailable { .. } => (
            SabiErrorCode::Durability,
            RetryDirective::DoNotRetry,
            "channel authority WAL/FULL durability is unavailable",
        ),
        ChannelBackendError::SchemaVersionUnsupported(_)
        | ChannelBackendError::CorruptRecord(_)
        | ChannelBackendError::LockPoisoned => (
            SabiErrorCode::Driver,
            RetryDirective::DoNotRetry,
            "local channel authority defect; do not retry",
        ),
    }
}

/// Typed `ChannelControl` SABI service bound to a [`ChannelControlBackend`]
/// (such as [`nlos_channel::ChannelAuthority`]) and a [`ChannelControlAuthorizer`].
pub struct ChannelControlService<'a, B, A = AllowAllChannelControlAuthorizer> {
    channel: &'a B,
    authorizer: A,
}

impl<'a, B, A> ChannelControlService<'a, B, A>
where
    B: ChannelControlBackend,
    A: ChannelControlAuthorizer,
{
    /// Binds a new `ChannelControl` service to `channel` and `authorizer`.
    #[must_use]
    pub const fn new(channel: &'a B, authorizer: A) -> Self {
        Self {
            channel,
            authorizer,
        }
    }

    /// Handles one validated SABI request envelope and returns the response
    /// envelope on success.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelControlError`] on context, schema, policy, or authority
    /// rejection. Failed requests never manufacture a success receipt.
    pub fn handle(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
        _now_wall_ms: i64,
    ) -> Result<Envelope, ChannelControlError> {
        if request.service != CHANNEL_CONTROL_SERVICE {
            return Err(ChannelControlError::UnknownMethod);
        }
        match request.method.as_str() {
            CREATE_CHANNEL_METHOD => self.handle_create_channel(request, now_monotonic_ns),
            ROTATE_CHANNEL_METHOD => self.handle_rotate_channel(request, now_monotonic_ns),
            ENQUEUE_METHOD => self.handle_enqueue(request, now_monotonic_ns),
            RECEIVE_METHOD => self.handle_receive(request, now_monotonic_ns),
            ACK_METHOD => self.handle_ack(request, now_monotonic_ns),
            COMPACT_METHOD => self.handle_compact(request, now_monotonic_ns),
            INSPECT_CHANNEL_METHOD => self.handle_inspect_channel(request, now_monotonic_ns),
            INSPECT_QUEUE_METHOD => self.handle_inspect_queue(request, now_monotonic_ns),
            REGISTER_QUEUE_CONSUMPTION_METHOD => {
                self.handle_register_queue_consumption(request, now_monotonic_ns)
            }
            _ => Err(ChannelControlError::UnknownMethod),
        }
    }

    /// Handles one request for a local IPC adapter and always returns a typed
    /// response [`Envelope`].
    #[must_use]
    pub fn handle_for_ipc(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
        now_wall_ms: i64,
    ) -> Envelope {
        match self.handle(request, now_monotonic_ns, now_wall_ms) {
            Ok(response) => response,
            Err(error) => failure_envelope(request, &error),
        }
    }

    fn handle_create_channel(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_create_channel_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let policy_digest = fixed32(&payload.policy_digest)?;
        self.authorizer
            .authorize(CREATE_CHANNEL_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (record, replayed) = self.channel.create_channel(
            payload.capacity_bytes,
            policy_digest,
            IdempotencyKey::from_bytes(idempotency_key),
            payload.created_at_ms,
        )?;
        let receipt = ReceiptReference {
            receipt_id: record.channel_id.clone(),
        };
        let result = payload::CreateChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            record: Some(record),
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_create_channel_result(&result)?,
            vec![receipt],
        ))
    }

    fn handle_rotate_channel(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_rotate_channel_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let channel_id = fixed16(&payload.channel_id)?;
        let expected_generation = NonZeroU64::new(payload.expected_generation)
            .map(Generation::new)
            .ok_or(ChannelControlError::InvalidGeneration)?;
        let expected_fencing_token = fixed32(&payload.expected_fencing_token)?;
        self.authorizer
            .authorize(ROTATE_CHANNEL_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (record, replayed) = self.channel.rotate_channel(
            channel_id,
            expected_generation,
            expected_fencing_token,
            IdempotencyKey::from_bytes(idempotency_key),
            payload.rotated_at_ms,
        )?;
        let receipt = ReceiptReference {
            receipt_id: idempotency_key.to_vec(),
        };
        let result = payload::RotateChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            record: Some(record),
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_rotate_channel_result(&result)?,
            vec![receipt],
        ))
    }

    fn handle_enqueue(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_enqueue_channel_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let channel_id = fixed16(&payload.channel_id)?;
        let expected_generation = NonZeroU64::new(payload.expected_generation)
            .map(Generation::new)
            .ok_or(ChannelControlError::InvalidGeneration)?;
        let expected_fencing_token = fixed32(&payload.expected_fencing_token)?;
        let producer = match (
            payload.producer_binding.is_empty(),
            payload.producer_fiber_generation,
        ) {
            (true, 0) => None,
            (false, generation) if generation > 0 => {
                let binding = fixed16(&payload.producer_binding)?;
                let fiber_generation = NonZeroU64::new(generation)
                    .map(Generation::new)
                    .ok_or(ChannelControlError::InvalidGeneration)?;
                Some((binding, fiber_generation))
            }
            _ => return Err(ChannelControlError::InvalidProducerRegistration),
        };
        self.authorizer
            .authorize(ENQUEUE_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (entry, replayed) = self.channel.enqueue(
            channel_id,
            expected_generation,
            expected_fencing_token,
            payload.payload,
            IdempotencyKey::from_bytes(idempotency_key),
            payload.enqueued_at_ms,
            producer,
        )?;
        let receipt = ReceiptReference {
            receipt_id: idempotency_key.to_vec(),
        };
        let result = payload::EnqueueChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            record: Some(entry),
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_enqueue_channel_result(&result)?,
            vec![receipt],
        ))
    }

    fn handle_receive(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::QUERY, now_monotonic_ns)?;
        let payload = decode_receive_channel_request(&request.payload)?;
        let channel_id = fixed16(&payload.channel_id)?;
        self.authorizer
            .authorize(RECEIVE_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let limit = usize::try_from(payload.limit)
            .unwrap_or(MAX_CHANNEL_RECEIVE_ENTRIES)
            .min(MAX_CHANNEL_RECEIVE_ENTRIES);
        let entries = self.channel.receive(channel_id, limit)?;
        let result = payload::ReceiveChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            entries,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_receive_channel_result(&result)?,
            Vec::new(),
        ))
    }

    fn handle_ack(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_ack_channel_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let channel_id = fixed16(&payload.channel_id)?;
        self.authorizer
            .authorize(ACK_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (consume_high_water, acked_at_ms, replayed) =
            self.channel
                .ack(channel_id, payload.up_to_sequence, payload.acked_at_ms)?;
        let receipt = ReceiptReference {
            receipt_id: idempotency_key.to_vec(),
        };
        let result = payload::AckChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            channel_id: channel_id.to_vec(),
            consume_high_water,
            acked_at_ms,
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_ack_channel_result(&result)?,
            vec![receipt],
        ))
    }

    fn handle_compact(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_compact_channel_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let channel_id = fixed16(&payload.channel_id)?;
        self.authorizer
            .authorize(COMPACT_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (trim_high_water, replayed) =
            self.channel.compact(channel_id, payload.trim_to_sequence)?;
        let receipt = ReceiptReference {
            receipt_id: idempotency_key.to_vec(),
        };
        let result = payload::CompactChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            channel_id: channel_id.to_vec(),
            trim_high_water,
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_compact_channel_result(&result)?,
            vec![receipt],
        ))
    }

    fn handle_inspect_channel(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::QUERY, now_monotonic_ns)?;
        let payload = decode_inspect_channel_request(&request.payload)?;
        let channel_id = fixed16(&payload.channel_id)?;
        self.authorizer
            .authorize(INSPECT_CHANNEL_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let record = self.channel.inspect_channel(channel_id)?;
        let result = payload::InspectChannelResultWire {
            schema: Some(channel_control_schema_identity()),
            record: Some(record),
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_inspect_channel_result(&result)?,
            Vec::new(),
        ))
    }

    fn handle_inspect_queue(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::QUERY, now_monotonic_ns)?;
        let payload = decode_inspect_queue_request(&request.payload)?;
        let channel_id = fixed16(&payload.channel_id)?;
        self.authorizer
            .authorize(INSPECT_QUEUE_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let state = self.channel.inspect_queue(channel_id)?;
        let result = payload::InspectQueueResultWire {
            schema: Some(channel_control_schema_identity()),
            state: Some(state),
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_inspect_queue_result(&result)?,
            Vec::new(),
        ))
    }

    fn handle_register_queue_consumption(
        &self,
        request: &Envelope,
        now_monotonic_ns: u64,
    ) -> Result<Envelope, ChannelControlError> {
        let context =
            validate_sabi_request_context(request, MethodSemantics::MUTATION, now_monotonic_ns)?;
        let payload = decode_register_queue_consumption_request(&request.payload)?;
        let idempotency_key = bind_idempotency_key(context, &payload.idempotency_key)?;
        let channel_id = fixed16(&payload.channel_id)?;
        let binding = fixed16(&payload.binding)?;
        let fiber_generation = NonZeroU64::new(payload.fiber_generation)
            .map(Generation::new)
            .ok_or(ChannelControlError::InvalidGeneration)?;
        self.authorizer
            .authorize(REGISTER_QUEUE_CONSUMPTION_METHOD, context)
            .map_err(ChannelControlError::AuthorizationDenied)?;
        let (record, replayed) = self.channel.register_queue_consumption(
            channel_id,
            payload.sequence,
            binding,
            fiber_generation,
            IdempotencyKey::from_bytes(idempotency_key),
            payload.registered_at_ms,
        )?;
        let receipt = ReceiptReference {
            receipt_id: record.registration_id.clone(),
        };
        let result = payload::RegisterQueueConsumptionResultWire {
            schema: Some(channel_control_schema_identity()),
            record: Some(record),
            replayed,
        };
        Ok(response_envelope(
            request,
            context.correlation_id.clone(),
            encode_register_queue_consumption_result(&result)?,
            vec![receipt],
        ))
    }
}

fn fixed16(bytes: &[u8]) -> Result<[u8; REQUEST_ID_BYTES], ChannelControlError> {
    bytes
        .try_into()
        .map_err(|_| ChannelControlError::InvalidIdentifier)
}

fn fixed32(bytes: &[u8]) -> Result<[u8; SHA256_DIGEST_BYTES], ChannelControlError> {
    bytes
        .try_into()
        .map_err(|_| ChannelControlError::InvalidIdentifier)
}

fn bind_idempotency_key(
    context: &SabiRequestContext,
    payload_key: &[u8],
) -> Result<[u8; REQUEST_ID_BYTES], ChannelControlError> {
    if payload_key != context.idempotency_key {
        return Err(ChannelControlError::IdempotencyKeyMismatch);
    }
    fixed16(payload_key)
}

/// Builds a typed failure [`Envelope`] for a rejected `ChannelControl` request.
#[must_use]
pub fn failure_envelope(request: &Envelope, error: &ChannelControlError) -> Envelope {
    let correlation_id = match request.common_context.as_ref() {
        Some(envelope::CommonContext::RequestContext(context))
            if context.correlation_id.len() == REQUEST_ID_BYTES =>
        {
            context.correlation_id.clone()
        }
        _ if request.request_id.len() == REQUEST_ID_BYTES => request.request_id.clone(),
        _ => vec![0; REQUEST_ID_BYTES],
    };
    let mut response = request.clone();
    response.payload.clear();
    response.common_context = Some(envelope::CommonContext::ResponseContext(
        SabiResponseContext {
            correlation_id,
            operation: None,
            receipts: Vec::new(),
            failure: Some(error.to_sabi_failure()),
        },
    ));
    response
}

fn response_envelope(
    request: &Envelope,
    correlation_id: Vec<u8>,
    payload: Vec<u8>,
    receipts: Vec<ReceiptReference>,
) -> Envelope {
    let mut response = request.clone();
    response.payload = payload;
    response.common_context = Some(envelope::CommonContext::ResponseContext(
        SabiResponseContext {
            correlation_id,
            operation: None,
            receipts,
            failure: None,
        },
    ));
    response
}

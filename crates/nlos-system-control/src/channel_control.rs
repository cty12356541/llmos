/// Typed backend error mirroring [`nlos_channel::ChannelAuthorityError`] across
/// feature configurations.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ChannelBackendError {
    Sqlite(String),
    Io(String),
    DurabilityUnavailable {
        journal_mode: String,
        synchronous: i64,
    },
    SchemaVersionUnsupported(i64),
    ChannelNotFound([u8; 16]),
    IdempotencyConflict,
    StaleChannel,
    InvalidCapacity,
    GenerationExhausted,
    QueueFull,
    InvalidPayload,
    InvalidSequence(&'static str),
    InvalidBindingRegistration,
    CorruptRecord(&'static str),
    LockPoisoned,
}

impl fmt::Display for ChannelBackendError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Sqlite(error) => write!(formatter, "SQLite channel authority failure: {error}"),
            Self::Io(error) => write!(formatter, "channel authority I/O failure: {error}"),
            Self::DurabilityUnavailable {
                journal_mode,
                synchronous,
            } => write!(
                formatter,
                "WAL/FULL durability unavailable: journal_mode={journal_mode}, synchronous={synchronous}"
            ),
            Self::SchemaVersionUnsupported(version) => {
                write!(
                    formatter,
                    "unsupported channel authority schema version {version}"
                )
            }
            Self::ChannelNotFound(id) => write!(formatter, "channel {id:02x?} does not exist"),
            Self::IdempotencyConflict => formatter.write_str(
                "idempotency key or authority-assigned identity was rebound to different input",
            ),
            Self::StaleChannel => {
                formatter.write_str("channel generation or fencing token is stale")
            }
            Self::InvalidCapacity => formatter.write_str("channel capacity must be non-zero"),
            Self::GenerationExhausted => formatter.write_str("channel generation space exhausted"),
            Self::QueueFull => {
                formatter.write_str("queue backlog plus payload exceeds channel capacity")
            }
            Self::InvalidPayload => formatter.write_str("queue payload must be non-empty"),
            Self::InvalidSequence(reason) => write!(formatter, "invalid queue sequence: {reason}"),
            Self::InvalidBindingRegistration => formatter.write_str(
                "fiber registration identity is invalid (zero binding or identity rebinding)",
            ),
            Self::CorruptRecord(reason) => write!(formatter, "corrupt channel record: {reason}"),
            Self::LockPoisoned => formatter.write_str("channel authority writer lock is poisoned"),
        }
    }
}

impl Error for ChannelBackendError {}

/// Backing authority trait for [`ChannelControlService`].
///
/// Implemented directly for [`nlos_channel::ChannelAuthority`] whenever the
/// `daemon` or `notify` feature (or unit test harness) is active.
pub trait ChannelControlBackend {
    /// Creates or replays a channel generation record.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on capacity, idempotency, or storage failure.
    fn create_channel(
        &self,
        capacity_bytes: u64,
        policy_digest: [u8; 32],
        idempotency_key: IdempotencyKey,
        created_at_ms: u64,
    ) -> Result<(payload::ChannelRecordWire, bool), ChannelBackendError>;

    /// Rotates a channel generation with expected generation and fence CAS.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel, stale fence, or conflict.
    fn rotate_channel(
        &self,
        channel_id: [u8; 16],
        expected_generation: Generation,
        expected_fencing_token: [u8; 32],
        idempotency_key: IdempotencyKey,
        rotated_at_ms: u64,
    ) -> Result<(payload::ChannelRecordWire, bool), ChannelBackendError>;

    /// Appends one payload to the channel queue (with optional producer registration).
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on stale fence, queue full, conflict, or invalid registration.
    #[allow(clippy::too_many_arguments)]
    fn enqueue(
        &self,
        channel_id: [u8; 16],
        expected_generation: Generation,
        expected_fencing_token: [u8; 32],
        payload: Vec<u8>,
        idempotency_key: IdempotencyKey,
        enqueued_at_ms: u64,
        producer: Option<([u8; 16], Generation)>,
    ) -> Result<(payload::QueueEntryRecordWire, bool), ChannelBackendError>;

    /// Reads the unacknowledged delivery window in sequence order up to `limit`.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel or storage corruption.
    fn receive(
        &self,
        channel_id: [u8; 16],
        limit: usize,
    ) -> Result<Vec<payload::QueueEntryRecordWire>, ChannelBackendError>;

    /// Advances the consume high-water mark to `up_to_sequence`.
    ///
    /// Returns `(consume_high_water, acked_at_ms, replayed)`.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel or invalid sequence.
    fn ack(
        &self,
        channel_id: [u8; 16],
        up_to_sequence: u64,
        acked_at_ms: u64,
    ) -> Result<(u64, u64, bool), ChannelBackendError>;

    /// Trims consumed queue entries up to `min(trim_to_sequence, consume_high_water)`.
    ///
    /// Returns `(trim_high_water, replayed)`.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel or regressing sequence.
    fn compact(
        &self,
        channel_id: [u8; 16],
        trim_to_sequence: u64,
    ) -> Result<(u64, bool), ChannelBackendError>;

    /// Inspects the current channel generation record.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel or corrupt head/generation state.
    fn inspect_channel(
        &self,
        channel_id: [u8; 16],
    ) -> Result<payload::ChannelRecordWire, ChannelBackendError>;

    /// Inspects the verified queue state of a channel.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on missing channel or bookkeeping mismatch.
    fn inspect_queue(
        &self,
        channel_id: [u8; 16],
    ) -> Result<payload::QueueStateWire, ChannelBackendError>;

    /// Registers a durable fiber queue consumption fact.
    ///
    /// # Errors
    ///
    /// Returns [`ChannelBackendError`] on invalid binding, missing entry, or conflict.
    #[allow(clippy::too_many_arguments)]
    fn register_queue_consumption(
        &self,
        channel_id: [u8; 16],
        sequence: u64,
        binding: [u8; 16],
        fiber_generation: Generation,
        idempotency_key: IdempotencyKey,
        registered_at_ms: u64,
    ) -> Result<(payload::QueueConsumptionRecordWire, bool), ChannelBackendError>;
}

